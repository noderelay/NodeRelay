// Exact shortcode → emoji; empty if unknown.
inline QString emojiForCode(QStringView code)
{
    for (const auto &e : kEmojiTable)
        if (e.shortcode == code)
            return e.ch.toString();
    return {};
}

inline QVector<EmojiEntry> emojiMatching(QStringView prefix)
{
    QVector<EmojiEntry> result;
    for (const auto &e : kEmojiTable)
        if (e.shortcode.startsWith(prefix, Qt::CaseInsensitive))
            result.append(e);
    return result;
}
